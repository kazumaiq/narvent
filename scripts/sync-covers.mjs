/**
 * Downloads official release artwork, stores it under a content-hashed filename
 * (`public/covers/<id>.<hash>.jpg`) and generates `src/data/coverManifest.ts`.
 *
 * Why hashed names: covers are served with long-lived cache headers. If a cover is
 * ever corrected, a new hash = new URL, so no browser/CDN can keep showing a stale
 * (wrong) image.
 *
 * Safety checks (the script fails loudly):
 *  - every source must download and be a real JPEG/PNG;
 *  - two different release IDs may never resolve to identical image bytes.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const coversDir = path.join(root, 'public', 'covers');
const sources = JSON.parse(fs.readFileSync(path.join(root, 'scripts', 'cover-sources.json'), 'utf8'));
delete sources._comment;

async function load(src) {
  if (src.startsWith('local:')) {
    const name = src.slice(6);
    const candidates = [path.join(root, 'scripts', 'artwork', name), path.join(coversDir, name)];
    const file = candidates.find((f) => fs.existsSync(f));
    if (!file) throw new Error(`local artwork not found: ${name}`);
    return fs.readFileSync(file);
  }
  const res = await fetch(src);
  if (!res.ok) throw new Error(`${res.status} for ${src}`);
  return Buffer.from(await res.arrayBuffer());
}

const isImage = (b) =>
  (b[0] === 0xff && b[1] === 0xd8) || (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47);

const manifest = {};
const seen = new Map();
const keep = new Set();

for (const [id, src] of Object.entries(sources)) {
  const buf = await load(src);
  if (!isImage(buf) || buf.length < 5000) throw new Error(`invalid image for ${id}`);
  const hash = crypto.createHash('sha256').update(buf).digest('hex');
  if (seen.has(hash)) throw new Error(`DUPLICATE ARTWORK: "${id}" is identical to "${seen.get(hash)}"`);
  seen.set(hash, id);
  const file = `${id}.${hash.slice(0, 10)}.jpg`;
  fs.writeFileSync(path.join(coversDir, file), buf);
  keep.add(file);
  manifest[id] = `/covers/${file}`;
  console.log(`✓ ${id.padEnd(24)} ${file}  (${(buf.length / 1024).toFixed(0)} KB)`);
}

// Keep the artist-supplied original (source for `local:`), drop every stale file.
fs.mkdirSync(path.join(root, 'scripts', 'artwork'), { recursive: true });
for (const f of fs.readdirSync(coversDir)) {
  if (keep.has(f)) continue;
  const localSrc = Object.values(sources).find((s) => s === `local:${f}`);
  if (localSrc) {
    fs.renameSync(path.join(coversDir, f), path.join(root, 'scripts', 'artwork', f));
    continue;
  }
  fs.unlinkSync(path.join(coversDir, f));
}

const body = Object.entries(manifest)
  .map(([id, url]) => `  '${id}': '${url}',`)
  .join('\n');
fs.writeFileSync(
  path.join(root, 'src', 'data', 'coverManifest.ts'),
  `// AUTO-GENERATED by scripts/sync-covers.mjs — do not edit by hand.\n// Maps a stable release ID to its content-hashed official artwork file.\nexport const coverManifest: Record<string, string> = {\n${body}\n};\n`
);
console.log(`\n${Object.keys(manifest).length} covers synced, all unique.`);
